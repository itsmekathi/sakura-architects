import { describe, expect, it } from 'vitest'
import { parseIndianPhone } from '@/lib/phone'

describe('parseIndianPhone', () => {
  it.each([
    ['98765 43210', '+91 98765 43210'],
    ['9876543210', '+91 98765 43210'],
    ['+91 98765 43210', '+91 98765 43210'],
    ['+91-98765-43210', '+91 98765 43210'],
    ['(+91) 98765-43210', '+91 98765 43210'],
    ['+919876543210', '+91 98765 43210'],
    ['919876543210', '+91 98765 43210'],
    ['09876543210', '+91 98765 43210'],
    ['6123456789', '+91 61234 56789'],
    ['011 2345 6789', '+91 11234 56789'],
    ['080-2345-6789', '+91 80234 56789'],
    ['+91 11 2345 6789', '+91 11234 56789'],
    ['(011) 2345 6789', '+91 11234 56789'],
  ])('accepts %s', (input, display) => {
    expect(parseIndianPhone(input)?.display).toBe(display)
  })

  it.each([
    '+44 20 7946 0958', // UK
    '+1 415 555 0123', // US
    '12345',
    '98765 4321', // 9 digits
    '98765 432100', // 11 digits, no 0 prefix
    '0123456789', // national number would start with 0
    '+91 0987654321',
    'abc9876543210',
    '98765 43210 ext 2',
    '',
  ])('rejects %s', (input) => {
    expect(parseIndianPhone(input)).toBeNull()
  })
})
